#!/usr/bin/env python3
"""Export a StreamingSNN checkpoint to a C++11 header."""
import argparse
import math
from pathlib import Path


def float_literal(value):
    value = float(value)
    if not math.isfinite(value):
        raise ValueError("The checkpoint contains a nonfinite value")
    literal = format(value, ".9g")
    if "." not in literal and "e" not in literal:
        literal += ".0"
    return literal + "f"


def initializer(values, indent=""):
    if not isinstance(values, list):
        return float_literal(values)
    if isinstance(values[0], list):
        rows = [indent + "  " + initializer(row, indent + "  ") for row in values]
        return "{\n" + ",\n".join(rows) + "\n" + indent + "}"
    entries = [float_literal(value) for value in values]
    if len(entries) <= 8:
        return "{" + ", ".join(entries) + "}"
    lines = [
        indent + "  " + ", ".join(entries[i:i + 8])
        for i in range(0, len(entries), 8)
    ]
    return "{\n" + ",\n".join(lines) + "\n" + indent + "}"


def render_header(state, gain, target_mean):
    width = state["fc1.weight"].shape[0]
    if width < 1 or not math.isfinite(gain) or gain <= 0:
        raise ValueError("Expected a positive model width and finite positive gain")
    use_skip = "skip.weight" in state
    tensors = [
        ("fc1.weight", "kFc1Weight[kWidth][64]", (width, 64)),
        ("fc1.bias", "kFc1Bias[kWidth]", (width,)),
        ("fc2.weight", "kFc2Weight[kWidth][kWidth]", (width, width)),
        ("fc2.bias", "kFc2Bias[kWidth]", (width,)),
        ("out.weight", "kOutWeight[1][kWidth]", (1, width)),
        ("out.bias", "kOutBias[1]", (1,)),
    ]
    if use_skip:
        tensors.append(("skip.weight", "kSkipWeight[1][64]", (1, 64)))

    if set(state) != {name for name, _, _ in tensors}:
        raise ValueError("Unexpected state_dict keys for StreamingSNN")

    lines = [
        "// Generated by tools/export_weights.py.",
        "#pragma once",
        "",
        f"#define SNN_HAS_SKIP {int(use_skip)}",
        "",
        "namespace snn_model {",
        f"constexpr int kWidth = {width};",
        f"constexpr float kGain = {float_literal(gain)};",
        f"constexpr float kTargetMean = {float_literal(target_mean)};",
        "",
    ]
    for name, declaration, shape in tensors:
        tensor = state[name]
        if tuple(tensor.shape) != shape:
            raise ValueError(f"{name} has shape {tuple(tensor.shape)}, expected {shape}")
        lines.append(f"constexpr float {declaration} = {initializer(tensor.tolist())};")
    lines.extend(["", "}  // namespace snn_model", ""])
    return "\n".join(lines)


def main():
    import torch

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()

    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    header = render_header(
        checkpoint["state_dict"], float(checkpoint["gain"]), float(checkpoint["target_mean"])
    )
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
